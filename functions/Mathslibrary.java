public class Mathslibrary {
    public static void main(String[] args) {
        System.out.println("Maximum "+Math.max(19, 230));
        System.out.println("Minimum "+Math.min(19, 230));
        System.out.println("squareroot "+Math.sqrt(19));
        System.out.println("power "+Math.pow(19, 230));
        System.out.println("absolute "+Math.abs(-8));
        System.out.println("roundoff "+Math.round(19.98));
        System.out.println("random "+Math.random());
    }
}
